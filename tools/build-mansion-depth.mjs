#!/usr/bin/env node
// Star Shard — generates mansion-depth.js, the tier-3 scholarship data for
// the Deep Chart's DEPTH tab (the four-tradition table, disagreements shown
// rather than smoothed, per PRODUCT.md §4).
//
//   node tools/build-mansion-depth.mjs
//
// Same category as tools/build-mansions.mjs: a one-time generator whose
// committed OUTPUT ships, source of truth is research/mansions-table.json
// (never hand-edit mansion-depth.js — see OWNERSHIP.md). Epithets are
// reused from build-mansions.mjs's own MANSION_EPITHETS rather than
// re-transcribed, so the two generators can't drift on station naming.
//
// OWNER: Claude Code.

import fs from 'node:fs';
import path from 'node:path';
import { MANSION_EPITHETS } from './build-mansions.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const RESEARCH = path.join(ROOT, 'research');

const table = JSON.parse(fs.readFileSync(path.join(RESEARCH, 'mansions-table.json'), 'utf8'));

const depth = table.map(m => ({
  id: m.id,
  epithet: MANSION_EPITHETS[m.id - 1].toLowerCase(),
  ar: m.translit_display,
  arMeaning: m.meaning_en,
  star: m.determinant_star,
  asterism: m.asterism.join(' · '),
  span: m.tropical_span,
  nkName: m.nakshatra.name,
  nkDeity: m.nakshatra.deity || '',
  nkSymbol: m.nakshatra.symbol || '',
  nkMatch: m.nakshatra.match || '',
  xChar: m.xiu.char,
  xPinyin: m.xiu.pinyin,
  xAnimal: m.xiu.animal,
  xQuadrant: m.xiu.quadrant,
  xMatch: m.xiu.match || '',
  kanji: m.sukuyo_kanji || '',
  match: m.match_overall || '',
  note: m.offset_note || '',
  gaps: (m.gaps || []).join(','),
}));

function js() {
  return '// Star Shard — generated tier-3 DEPTH data for the Deep Chart.\n' +
    '// Generated by tools/build-mansion-depth.mjs from research/mansions-table.json\n' +
    '// — regenerate, never hand-edit (see OWNERSHIP.md).\n\n' +
    `window.MANSION_DEPTH = ${JSON.stringify(depth)};\n`;
}

function writeAll() {
  fs.writeFileSync(path.join(ROOT, 'mansion-depth.js'), js());
  console.log(`generated mansion-depth.js — ${depth.length} stations, ` +
    `${depth.filter(d => d.nkDeity).length} with a nakshatra deity`);
}

if (import.meta.url === `file://${process.argv[1]}`) writeAll();

export { depth, js, writeAll };
