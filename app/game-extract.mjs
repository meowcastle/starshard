#!/usr/bin/env node
// game-extract.mjs: the shard reveal's own assets, lifted from the shipped game (SS7, 1 Nov 2026).
//
// The game ("Star Shard v3 Build Plan/Manzil - Game Prototype V2.dc.html") reveals a shard as
// a name in Cormorant, two cards (the sun's station and the moon's) carrying the station art
// from manzil-art2.js, and one line of observation per station (its _mPoem table). This script
// reads those out of the game's own files so app/ draws the same cards from the same bytes:
//
//   app/src/station-art.json   { "1": [ { d, f, s, w, da, st } ... ], ... "28": [...] }
//   app/src/station-art.css    the keyframes those shapes animate with, verbatim from the game
//   app/src/station-poems.json the 28 lines, in station order
//
// Run from the repo root when the game file or manzil-art2.js changes:
//   node app/game-extract.mjs
// The build never reads the game file; it imports these three.
import { readFileSync, writeFileSync } from 'node:fs';
import { createContext, runInContext } from 'node:vm';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const GAME = join(root, 'Star Shard v3 Build Plan', 'Manzil - Game Prototype V2.dc.html');
const ART = join(root, 'manzil-art2.js');

// the art: manzil-art2.js sets window.ManzilArt inside an IIFE; run it in a bare context
const ctx = createContext({ window: {} });
runInContext(readFileSync(ART, 'utf8'), ctx, { filename: 'manzil-art2.js' });
const art = {};
for (let m = 1; m <= 28; m++) art[m] = ctx.window.ManzilArt.get(m).map(p => ({ d: p.d, f: p.f, s: p.s, w: p.w, da: p.da, st: p.st }));
writeFileSync(join(here, 'src', 'station-art.json'), JSON.stringify(art));

const game = readFileSync(GAME, 'utf8');

// the keyframes the shapes name (bsBreathe, bsTwinkle, bsRain, ...), from the game's own style
const names = new Set();
for (const m of Object.values(art)) for (const p of m) { const k = /animation:([A-Za-z0-9]+)/.exec(p.st || ''); if (k) names.add(k[1]); }
const css = [];
for (const name of [...names].sort()) {
  const re = new RegExp(`@keyframes ${name}\\{[^}]*\\}(?:[^}]*\\})*?\\}`);
  const m = re.exec(game);
  if (!m) throw new Error(`no keyframes ${name} in the game file`);
  css.push(m[0]);
}
writeFileSync(join(here, 'src', 'station-art.css'), `/* generated by app/game-extract.mjs from the shipped game: the keyframes the station art names */\n${css.join('\n')}\n`);

// the 28 lines of observation, the game's _mPoem table
const i = game.indexOf('_mPoem(m) { return [');
if (i < 0) throw new Error('no _mPoem in the game file');
const j = game.indexOf('][(m || 1) - 1]', i);
const body = game.slice(i + '_mPoem(m) { return ['.length, j);
const poems = [...body.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(m => JSON.parse(`"${m[1]}"`));
if (poems.length !== 28) throw new Error(`${poems.length} poems, wanted 28`);
writeFileSync(join(here, 'src', 'station-poems.json'), JSON.stringify(poems, null, 1));

console.log(`station-art.json: 28 stations, ${Object.values(art).reduce((n, m) => n + m.length, 0)} shapes; station-art.css: ${css.length} keyframes (${[...names].sort().join(', ')}); station-poems.json: 28 lines`);
